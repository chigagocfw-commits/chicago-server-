    if entities[1] == PlayerPedId() and not alreadyDead then
        JustDied()
    end
end)

AddEventHandler("CEventEntityDamaged", function()
    if IsPedDeadOrDying(PlayerPedId(), false) and not alreadyDead then
        JustDied()
    end
end)

